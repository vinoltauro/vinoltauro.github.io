// Generates src/components/icon-paths.ts: the "regular" weight of every Phosphor icon the site
// uses, as raw SVG markup. Run after adding an icon to the map in Icon.tsx:  node scripts/build-icons.mjs
import { readFileSync, writeFileSync } from 'node:fs'
import { createElement } from 'react'
import { renderToStaticMarkup } from 'react-dom/server'

const root = new URL('..', import.meta.url).pathname
const src = readFileSync(`${root}src/components/Icon.tsx`, 'utf8')
const block = src.slice(src.indexOf('const icons = {'), src.indexOf('} as const'))
const pairs = [...block.matchAll(/^\s+([a-z]+): '?([A-Za-z]+)'?,?$/gm)].map((m) => [m[1], m[2]])

const out = {}
for (const [key, comp] of pairs) {
  const mod = await import(`${root}node_modules/@phosphor-icons/react/dist/defs/${comp}.es.js`)
  const weights = Object.values(mod).find((v) => v instanceof Map)
  out[key] = renderToStaticMarkup(weights.get('regular'))
}
writeFileSync(
  `${root}src/components/icon-paths.ts`,
  `// Generated by scripts/build-icons.mjs from Phosphor Icons (MIT), regular weight only. Do not edit.\nexport const iconPaths = ${JSON.stringify(out, null, 2)} as const\n`,
)
console.log(`wrote ${pairs.length} icons`)
